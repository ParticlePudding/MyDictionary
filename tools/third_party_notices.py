#!/usr/bin/env python3
"""THIRD-PARTY-NOTICES.txt を作り直す。

MyDictionary.exe に組み込まれる(Windows x64 で実行時にリンクされる)クレートを
`cargo tree` で調べ、各クレートに同梱されている MIT ライセンスの文面を集めて、
リポジトリ直下の THIRD-PARTY-NOTICES.txt に書き出す。

依存を更新したら(Cargo.lock が変わったら)、リポジトリ直下で実行する:

    python tools/third_party_notices.py

ビルドだけに使うクレート(build-dependencies)や、手続きマクロとその依存は、
exe に含まれないので対象外。
"""

import json
import pathlib
import re
import subprocess
import sys
import textwrap

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.txt"
TARGET = "x86_64-pc-windows-msvc"
RULE = "=" * 79
SUB = "-" * 79

# クレート以外に exe に含まれるもの
SQLITE_BLESSING = """\
The author disclaims copyright to this source code. In place of
a legal notice, here is a blessing:

    May you do good and not evil.
    May you find forgiveness for yourself and forgive others.
    May you share freely, never taking more than you give."""


def run(*args):
    return subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True, encoding="utf-8").stdout


def runtime_crates():
    out = run("cargo", "tree", "--locked", "--target", TARGET, "-e", "normal,no-proc-macro",
              "--prefix", "none", "--format", "{p}")
    found = set()
    for line in out.splitlines():
        m = re.match(r"^(\S+) v(\S+)", line)
        if m:
            found.add((m.group(1), m.group(2)))
    return found


def normalize(text):
    lines = [l.rstrip() for l in text.replace("\r\n", "\n").replace("\r", "\n").split("\n")]
    return textwrap.dedent("\n".join(lines)).strip("\n")


def mit_text(pkg):
    d = pathlib.Path(pkg["manifest_path"]).parent
    files = {p.name.lower(): p for p in d.iterdir() if p.is_file()}
    for name in ("license-mit", "license-mit.md", "license-mit.txt", "license", "license.md", "license.txt"):
        if name in files:
            text = normalize(files[name].read_text(encoding="utf-8"))
            if "Permission is hereby granted, free of charge" in text:
                return text
    sys.exit(f"MIT ライセンスの文面が見つかりません: {pkg['name']} {pkg['version']} ({d})")


def sqlite_version(pkg):
    h = pathlib.Path(pkg["manifest_path"]).parent / "sqlite3" / "sqlite3.h"
    m = re.search(r'#define SQLITE_VERSION\s+"([^"]+)"', h.read_text(encoding="utf-8", errors="replace"))
    return m.group(1) if m else None


def main():
    meta = json.loads(run("cargo", "metadata", "--locked", "--format-version", "1"))
    root_name = meta["packages"][[p["id"] for p in meta["packages"]].index(meta["resolve"]["root"])]["name"]
    wanted = runtime_crates()
    pkgs = sorted(
        (p for p in meta["packages"] if (p["name"], p["version"]) in wanted and p["name"] != root_name),
        key=lambda p: (p["name"], p["version"]),
    )

    rows = []      # (名前, 版, ライセンス, URL, 作者)
    groups = {}    # 文面 -> [名前 版]
    sqlite = None
    for p in pkgs:
        url = p.get("repository") or p.get("homepage") or f"https://crates.io/crates/{p['name']}"
        authors = ", ".join(re.sub(r"\s*<[^>]*>", "", a) for a in p.get("authors") or [])
        rows.append((p["name"], p["version"], p["license"], url, authors))
        groups.setdefault(mit_text(p), []).append(f"{p['name']} {p['version']}")
        if p["name"] == "libsqlite3-sys":
            sqlite = sqlite_version(p)

    # Rust の標準ライブラリ(MIT OR Apache-2.0)。どの exe にも静的にリンクされる
    rows.append(("Rust standard library", "", "MIT OR Apache-2.0", "https://github.com/rust-lang/rust", "The Rust Project Developers"))
    generic = next((t for t in groups if not re.search(r"(?i)copyright\s*(\(c\)|©|\d{4})", t)), None)
    if generic is None:
        sys.exit("Rust 標準ライブラリに当てる MIT の文面(著作権行の無いもの)が見つかりません")
    groups[generic].append("Rust standard library")

    if sqlite:
        rows.append(("SQLite", sqlite, "Public Domain", "https://www.sqlite.org/", "D. Richard Hipp and contributors"))

    out = []
    w = out.append
    w("THIRD-PARTY SOFTWARE NOTICES AND INFORMATION")
    w("")
    w("MyDictionary は、以下のオープンソースソフトウェアを使用しています。")
    w("MyDictionary uses the open source software listed below.")
    w("")
    w("Each component is distributed under the license shown with it. Where a")
    w("component is offered under a choice of licenses (for example, \"MIT OR")
    w("Apache-2.0\"), MyDictionary uses it under the terms of the MIT License.")
    w("")
    w("This file is generated by tools/third_party_notices.py.")
    w("")
    w(RULE)
    w("Components")
    w(RULE)
    w("")
    for name, ver, lic, url, authors in rows:
        w(f"{name} {ver}".rstrip())
        w(f"  License: {lic}")
        w(f"  Source:  {url}")
        if authors:
            w(f"  Authors: {authors}")
        w("")
    for text, users in groups.items():
        w(RULE)
        w("MIT License")
        w("")
        w("Used by:")
        for u in users:
            w(f"  {u}")
        w(SUB)
        w("")
        w(text)
        w("")
    if sqlite:
        w(RULE)
        w("Public Domain")
        w("")
        w("Used by:")
        w(f"  SQLite {sqlite} (bundled with libsqlite3-sys)")
        w(SUB)
        w("")
        w(SQLITE_BLESSING)
        w("")
    w(RULE)
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{OUT.name}: {len(rows)} components")


if __name__ == "__main__":
    main()
